.segment "CODE"

; --- upload to the SPC700 --------------------------------------------------
; SNES audio is run by the SPC700, a separate processor with its own 64 KB of
; memory. The 65816 cannot touch the DSP directly: it can only talk to the
; SPC700 through four ports.
;
; At power-on the SPC700 runs an internal ROM that implements an upload
; protocol. We use it to put a minimal driver and the sample directory into
; its memory —the samples go later, in packages: see `package_load`—, and
; then that driver sits waiting for commands from the 65816, mostly DSP
; (register, value) pairs: see `DRIVER` in tools/audio/snes_music.py. In other
; words, all the music is still driven by the 65816.
;
; The protocol of the SPC700's internal ROM:
;
;   1. Wait for it to greet with $AA on port 0 and $BB on port 1.
;   2. Send it the destination address on ports 2 and 3, a nonzero value on
;      port 1, and $CC on port 0. It answers with the same $CC.
;   3. Each byte goes on port 1 and its index on port 0; it answers the index.
;   4. To start another block: the new address, something nonzero on port 1,
;      and the last index plus two on port 0.
;   5. To finish: the entry address, a zero on port 1, and the last index
;      plus two on port 0. There it jumps and starts the driver.
;
; The $CC of step 2 is sent only the first time; after that it sends the
; index plus two.
.proc spc_upload
.a8
.i16
wait_ready:
    lda APUIO0
    cmp #$AA
    bne wait_ready
    lda APUIO1
    cmp #$BB
    bne wait_ready

    lda #$CC                    ; the start of the first block is fixed
    sta port0

    ; --- the driver ---
    ldx #.loword(spc_driver)
    stx source
    lda #^spc_driver
    sta source + 2
    ldx #SPC_DRIVER_ADDR
    ldy #SPC_DRIVER_SIZE
    jsr spc_block

    ; --- the samples and their directory ---
    ; A map without music has no samples, and a block of zero bytes is not a
    ; block: the IPL protocol asks for an address, a port at nonzero and the
    ; index, and nobody answers on the other side. The ROM sat waiting in
    ; `wait_start` with the screen already on and the map drawn, that is,
    ; looking for all the world like it worked. It stayed hidden while
    ; `musicdata.inc` was generated by a separate recipe and always had a
    ; song; it showed up as soon as the converter started emitting each
    ; map's music, and most maps have none.
    ldy #SPC_SAMPLES_SIZE
    cpy #$0000
    beq no_samples
    ldx #.loword(spc_samples)
    stx source
    lda #^spc_samples
    sta source + 2
    ldx #SPC_SAMPLES_ADDR
    ldy #SPC_SAMPLES_SIZE
    jsr spc_block
no_samples:

    ; --- close and jump to the driver ---
    ldx #SPC_DRIVER_ADDR
    stx APUIO2
    stz APUIO1                  ; zero on port 1 = execute
    lda port0
    sta APUIO0
wait_jump:
    cmp APUIO0
    bne wait_jump

    stz token
    rts
.endproc

; --- one block of the upload ----------------------------------------------
; X = destination address, Y = how many bytes, source = where they come from.
; port0 brings the value to start with and is left ready for the next block.
.proc spc_block
.a8
.i16
    stx APUIO2                  ; destination address
    lda #$01
    sta APUIO1                  ; nonzero = keep transferring
    lda port0
    sta APUIO0
wait_start:
    cmp APUIO0
    bne wait_start

    ldx #$0000                  ; the index starts at zero in each block
send:
    cpy #$0000
    beq done
    lda [source]
    sta APUIO1
    txa
    sta APUIO0
wait_byte:
    cmp APUIO0
    bne wait_byte

    inx
    dey
    ; The same bank crossing as in `advance`: the samples go past 32 KB, so
    ; the upload to the SPC700 also crosses from one LoROM bank to the next.
    inc source
    bne send
    inc source + 1
    bne send
    lda #$80
    sta source + 1
    inc source + 2
    bra send

done:
    ; The next block starts with the last index plus two.
    txa
    inc a
    inc a
    sta port0
    rts
.endproc

